#!/usr/bin/env python3
"""Reduce la imagen del icono y le pone el texto con letras de pixel nitidas."""
import sys
from PIL import Image
F5 = {'A': ['010','101','111','101','101'], 'M': ['10001','11011','10101','10001','10001'],
      'I': ['111','010','010','010','111'], 'G': ['011','100','101','101','011'],
      'T': ['111','010','010','010','010'], 'R': ['110','101','110','101','101'],
      'O': ['010','101','101','101','010'], 'N': ['1001','1101','1011','1001','1001'],
      'C': ['011','100','100','100','011'], 'S': ['011','100','010','001','110']}
F7 = {'S': ['0111','1000','1000','0110','0001','0001','1110'], 'k': ['1000','1000','1001','1010','1100','1010','1001'],
      'i': ['1','0','1','1','1','1','1'], 'n': ['0000','0000','1110','1001','1001','1001','1001'],
      'P': ['1110','1001','1001','1110','1000','1000','1000'], 'a': ['0000','0000','0110','0001','0111','1001','0111'],
      't': ['010','010','111','010','010','010','001'], 'c': ['000','000','011','100','100','100','011'],
      'h': ['1000','1000','1110','1001','1001','1001','1001']}
F6 = {'A': ['0110','1001','1001','1111','1001','1001'], 'M': ['10001','11011','10101','10001','10001','10001'],
      'I': ['111','010','010','010','010','111'], 'G': ['0111','1000','1000','1011','1001','0111'],
      'T': ['11111','00100','00100','00100','00100','00100'], 'R': ['1110','1001','1001','1110','1010','1001'],
      'O': ['0110','1001','1001','1001','1001','0110'], 'N': ['1001','1101','1101','1011','1011','1001'],
      'C': ['0111','1000','1000','1000','1000','0111'], 'S': ['0111','1000','0110','0001','0001','1110']}
def bits(text, font, bold, gap=1):
    cols = []
    for ch in text:
        g = font[ch]; w = len(g[0]); h = len(g)
        for x in range(w + (1 if bold else 0)):
            cols.append([(x < w and g[y][x] == '1') or (bold and x > 0 and g[y][x - 1] == '1') for y in range(h)])
        for _ in range(gap): cols.append([False] * h)
    return cols[:-gap]
def stamp(im, text, font, bold, cx, y, gap=1):
    cols = bits(text, font, bold, gap); w = len(cols); h = len(cols[0]); x0 = round(cx - w / 2)
    px = im.load(); on = {(x0 + i, y + j) for i, c in enumerate(cols) for j, v in enumerate(c) if v}
    for (x, yy) in on:
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                p = (x + dx, yy + dy)
                if p not in on and 0 <= p[0] < im.width and 0 <= p[1] < im.height: px[p] = (0, 0, 0, 255)
    for p in on: px[p] = (255, 255, 255, 255)
def make(src, h):
    im = Image.open(src).convert('RGBA'); W0, H0 = im.size
    w = round(W0 * h / H0); s = h / H0
    im = im.resize((w, h), Image.LANCZOS)
    stamp(im, 'AMIGATRONICS', F6, False, 585 * s, round(865 * s) - 3, 1)
    stamp(im, 'SkinPatch', F7, True, 625 * s, round(1030 * s) - 3)
    return im
if __name__ == '__main__':
    make(sys.argv[1], int(sys.argv[3])).save(sys.argv[2])
